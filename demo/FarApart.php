<?php

class FarApart
{
    public function first($a, $b)
    {
        return $a+$b;
    }

    public function second()
    {
        return 2;
    }

    public function third()
    {
        return 3;
    }

    public function fourth()
    {
        return 4;
    }

    public function last($a, $b)
    {
        return $a+$b+1;
    }
}
